#!/usr/bin/env python3
"""Generate a self-contained HTML map viewer for Ultima II sector maps.

Why: the tile table is not 64 terrains (see docs/passability-findings.md F13). It
mixes ground, structures, creatures, borders and the A-Z shop/sign fixtures, and
the only way to see that is to look at real maps. This renders the shipped
mapxNN files with the real tile art, in a browser, with no server.

Output is one HTML file with everything embedded: the 64 tile PNGs as data URIs,
every sector's 4096 tile bytes, and the tile-art.tsv descriptions. Open it
directly; it makes no network requests.

Sectors are named from `disasm/place-index.tsv`, which is generated by
`tools/place_index.py` -- the viewer never hand-copies a name. Two content layers are
loaded and kept apart, because they are not the same worlds: `mapx` in the content root is
Earth's five eras plus Planet X, and `MAPG` in `updated/` is the Galaxy patch's Mercury
through Pluto. They share filenames only because MS-DOS had no directories; see
`docs/planet-maps-galaxy-patch.md`. Tile art is indexed `byte >> 2`, which is the art index;
`byte >> 1` is the gate value and is a different quantity.

`--serve` hosts it instead of writing it, for anyone on the LAN who is not sitting
on this machine — which is the usual case when the owner is testing a build on
another box. The served document is held in memory and there is no filesystem
root, on purpose; see serve().

Read-only by construction. It reads original/ and tmp/tiles/ and writes only to
the --out path, refusing to write into original/ or references/.

Usage:
    python3 tools/tile_atlas.py --out tmp/tiles        # first, if tiles missing
    python3 tools/map_viewer.py -o tmp/map-viewer.html
    python3 tools/map_viewer.py --serve                # http://<this host>:8099/
"""
import argparse
import base64
import glob
import json
import os
import sys

TILE_PX = 16          # art is 16x16; PNGs are upscaled, drawn with smoothing off
GRID = 64
TAIL = 128            # 4224 - 4096; byte 4096 is the 0x1A marker, not terrain


def load_tiles(tiledir, optional=False):
    """Extracted original art: 16x16 PNGs, one per art index."""
    tiles = {}
    for n in range(64):
        p = os.path.join(tiledir, 'tile_%02X.png' % n)
        if not os.path.exists(p):
            p = os.path.join(tiledir, 'tile_%02x.png' % n)
        if not os.path.exists(p):
            if optional:
                return {}
            sys.exit('missing tile %s; run tools/tile_atlas.py --out %s' % (p, tiledir))
        tiles[n] = 'data:image/png;base64,' + base64.b64encode(open(p, 'rb').read()).decode()
    return tiles


def load_cleanroom(dirpath, optional=True):
    """Cleanroom substitute art: SVGs.

    The committed SVGs carry a viewBox but no width/height, which is correct for
    an image asset but leaves them with no intrinsic size, and drawImage will not
    scale an SVG that has none. The attributes are injected here at embed time so
    the art files themselves stay untouched.
    """
    tiles = {}
    for n in range(64):
        p = os.path.join(dirpath, 'tile_%02X.svg' % n)
        if not os.path.exists(p):
            if optional:
                return {}
            sys.exit('missing cleanroom tile %s' % p)
        svg = open(p).read()
        if 'width=' not in svg.split('>', 1)[0]:
            svg = svg.replace('<svg ', '<svg width="16" height="16" ', 1)
        tiles[n] = 'data:image/svg+xml;base64,' + base64.b64encode(svg.encode()).decode()
    return tiles


def load_art(tsv):
    art = {}
    with open(tsv) as f:
        for line in f:
            line = line.rstrip('\n')
            if not line or line.startswith('#'):
                continue
            p = line.split('\t')
            if len(p) < 5 or p[1].strip() == 'id':
                continue
            a = int(p[1].strip(), 16)
            art[a] = {'kind': p[3].strip(), 'desc': p[4].strip(),
                      'note': p[6].strip() if len(p) > 6 else ''}
    return art


def load_places(tsv):
    """(layer, sector) -> naming, read from disasm/place-index.tsv.

    This is the authority for what a sector IS, and it is generated by
    tools/place_index.py -- the viewer must not hand-copy names, because a second
    hand-maintained list drifts and then lies. It is also the only place that resolves the
    mapx/MAPG collision correctly per sector: sector 41 is Earth's 2112 A.D. Aftermath on
    the `mapx` layer and Jupiter on the `mapg` layer, and no rule over the tens digit can
    say that, because the two layers share filenames for exactly the reason documented in
    docs/planet-maps-galaxy-patch.md.
    """
    out = {}
    if not os.path.exists(tsv):
        return out
    rows = [l.rstrip('\n').split('\t') for l in open(tsv)
            if l.strip() and not l.startswith('#')]
    if not rows:
        return out
    idx = {n: i for i, n in enumerate(rows[0])}
    need = ('layer', 'sector', 'world', 'era', 'kind', 'rooms', 'note')
    if not all(k in idx for k in need):
        print('warning: %s lacks %s; sector names unavailable'
              % (tsv, ','.join(k for k in need if k not in idx)))
        return out
    for r in rows[1:]:
        if len(r) <= max(idx.values()):
            continue
        sec = r[idx['sector']].strip()
        if not sec:
            continue
        out[(r[idx['layer']].strip(), sec)] = {
            'world': r[idx['world']].strip(),
            # "2112 A.D. Aftermath (ANOS: 2112 A.D.)" -> "2112 A.D. Aftermath": the ANOS
            # parenthetical is the in-game string, useful in the index, noise in a dropdown.
            'era': r[idx['era']].split(' (ANOS')[0].strip(),
            'kind': r[idx['kind']].strip(),
            # The decoded place names live in the column the generator calls `rooms` -- the
            # text runs naming a room or area. `dialogue` is the count of tlkx lines, not
            # text, and reading it as names is a mistake worth naming because it was made:
            # it produced a glyph count where a place name should be, which looks plausible.
            'names': r[idx['rooms']].strip(),
            'wiki': r[idx['wiki']].strip() if 'wiki' in idx else '',
            'note': r[idx['note']].strip(),
        }
    return out


def load_maps(srcdir, updated=None):
    """The root `mapx` set plus, when present, the Galaxy patch's `MAPG` set.

    Two layers, tagged, because they are not the same worlds. `mapx` is Earth's five eras
    and Planet X; `MAPG` is Mercury..Pluto, restored by the fan patch into `updated/`. The
    root set is missing the planet maps precisely because MS-DOS had no directories and
    `MAPG10` and `mapx10` were the same name -- so a viewer that reads only `mapx` shows a
    game with one planet and looks completely healthy doing it.
    """
    maps = []
    for path in sorted(glob.glob(os.path.join(srcdir, 'mapx*'))):
        name = os.path.basename(path)
        data = open(path, 'rb').read()
        if len(data) != GRID * GRID + TAIL:
            print('  note: %s is %d bytes, expected %d' % (name, len(data), GRID * GRID + TAIL))
        maps.append({'name': name, 'layer': 'mapx', 'sector': name[4:],
                     'bytes': list(data[:GRID * GRID])})
    nmapg = 0
    if updated and os.path.isdir(updated):
        for path in sorted(glob.glob(os.path.join(updated, 'MAPG*'))):
            name = os.path.basename(path)
            data = open(path, 'rb').read()
            if len(data) < GRID * GRID:
                print('  note: %s is %d bytes, shorter than a sector' % (name, len(data)))
                continue
            maps.append({'name': name, 'layer': 'mapg', 'sector': name[4:],
                         'bytes': list(data[:GRID * GRID])})
            nmapg += 1
    if not maps:
        sys.exit('no mapx* found in %s' % srcdir)
    return maps, nmapg


def name_maps(maps, places):
    """Attach display labels from the generated place index.

    Group label is per (layer, tens digit): Earth's five eras are five groups on the mapx
    layer, and the same five digits are five different planets on the mapg layer.
    """
    for m in maps:
        p = places.get((m['layer'], m['sector']))
        world = (p or {}).get('world') or ''
        era = (p or {}).get('era') or ''
        kind = (p or {}).get('kind') or ''
        names = (p or {}).get('names') or ''
        wiki = (p or {}).get('wiki') or ''
        m['world'] = world
        m['era'] = era
        m['kind'] = kind
        m['names'] = names
        head = world.title() if world else 'sector ' + m['sector']
        m['grouplabel'] = ' · '.join(x for x in (head, era) if x) or ('group ' + m['sector'][0])
        # Prefer the game's own decoded text; fall back to a wiki label only where the tiles
        # spell nothing, which is the case for most towers and dungeons.
        shown = '; '.join([n for n in names.split('; ') if n][:2]) or (wiki and wiki + ' (wiki)')
        m['label'] = ' · '.join(x for x in (m['sector'] + ' ' + kind, shown) if x) or m['name']
    return maps


