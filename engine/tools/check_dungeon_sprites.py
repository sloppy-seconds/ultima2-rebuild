#!/usr/bin/env python3
"""check_dungeon_sprites.py — prove the committed generated header still matches
the generator's own tables, without running the generator.

Why this exists: engine/src/game/dungeon_sprites_gen.h is committed generated
output, in the same class as content/gen_content.h, src/core/licenses_data.h and
content/fmtowns_map.h. Those three each have a `*-check` target. This one had
none, which is the failure AGENTS.md names outright: a generated artefact with no
freshness check goes stale and keeps reporting healthy.

Why the check is structural and NOT a byte comparison: the generator uses rembg
and pngquant when they are present and falls back to in-file implementations when
they are not, so the emitted art differs by host. A byte-compare would therefore
fail on a clean checkout even when the committed header is exactly right, and a
gate that cries wolf gets ignored — which is worse than no gate, because the real
drift then walks past it. The byte-exact comparison belongs in
deploy/art-pipeline/, where the tools exist and the output is reproducible.

What this does catch is the realistic drift: a sprite added to SPRITES without
regenerating the header, a sprite removed but still emitted, a renamed concept
file, or an EDGE/PAL_N change that never reached the header. Those are all
inconsistencies between two files in the repo, and they are checkable on any host.

Stdlib only, and it parses the generator's source rather than importing it, so
the gate does not acquire numpy and Pillow as dependencies. The generator needs
them; a checker that only compares tables does not, and a gate should not drag in
more than it uses.
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ENGINE = HERE.parent
GEN = HERE / "gen_dungeon_sprites.py"
HEADER = ENGINE / "src" / "game" / "dungeon_sprites_gen.h"
CONCEPTS = ENGINE.parent / "concepts" / "dungeon2"

SPRITE_RE = re.compile(r'^\s*\(\s*"([^"]+)"\s*,\s*"([^"]+)"')
CONST_RE = lambda n: re.compile(rf"^{n}\s*=\s*(\d+)", re.M)
HDR_DEFINE = lambda n: re.compile(rf"^#define\s+DG_SPR_{n}\s+(\d+)", re.M)
HDR_SPRITE_RE = re.compile(r"^static const uint8_t dg_spr_([a-z0-9_]+)\[", re.M)
GENERATOR_TAG = "GENERATED by engine/tools/gen_dungeon_sprites.py"


def parse_sprites(text: str) -> "list[tuple[str, str]]":
    """(concept stem, C symbol suffix) for every SPRITES entry."""
    m = re.search(r"^SPRITES\s*=\s*\[(.*?)^\]", text, re.M | re.S)
    if not m:
        sys.exit("check_dungeon_sprites: no SPRITES table found in "
                 f"{GEN.relative_to(ENGINE.parent)} — the checker's assumption "
                 "about the generator's shape no longer holds, fix the checker "
                 "before trusting its verdict")
    block = m.group(1)
    out = []
    for line in block.splitlines():
        if line.lstrip().startswith("#"):
            continue
        g = SPRITE_RE.match(line)
        if g:
            out.append((g.group(1), g.group(2)))
    return out


def parse_const(text: str, name: str) -> "int | None":
    g = CONST_RE(name).search(text)
    return int(g.group(1)) if g else None


def parse_define(text: str, name: str) -> "int | None":
    g = HDR_DEFINE(name).search(text)
    return int(g.group(1)) if g else None


def main() -> int:
    for p in (GEN, HEADER):
        if not p.is_file():
            print(f"check_dungeon_sprites: {p} is missing", file=sys.stderr)
            return 1

    gen_text = GEN.read_text()
    hdr_text = HEADER.read_text()

    sprites = parse_sprites(gen_text)
    if not sprites:
        print("check_dungeon_sprites: SPRITES table is empty — a checker that "
              "compares nothing reports success and means nothing", file=sys.stderr)
        return 1

    fails: "list[str]" = []

    want = [name for _stem, name in sprites]
    have = HDR_SPRITE_RE.findall(hdr_text)
    missing = [n for n in want if n not in have]
    extra = [n for n in have if n not in want]
    if missing:
        fails.append("in SPRITES but not emitted in the header: " + ", ".join(missing)
                     + " — regenerate with `make dungeon-sprites`")
    if extra:
        fails.append("emitted in the header but no longer in SPRITES: " + ", ".join(extra)
                     + " — the header is stale against the table")

    for const, define in (("EDGE", "EDGE"), ("PAL_N", "PAL_N")):
        g = parse_const(gen_text, const)
        h = parse_define(hdr_text, define)
        if g is None or h is None:
            fails.append(f"could not read {const} from the generator or DG_SPR_{define} "
                         "from the header — the checker's patterns are out of date")
        elif g != h:
            fails.append(f"{const}: generator says {g}, header says {h}")

    if GENERATOR_TAG not in hdr_text:
        fails.append("header does not carry the GENERATED-by line — either it was "
                     "hand-edited or the generator's banner changed; both need a "
                     "human, not a regeneration")

    if CONCEPTS.is_dir():
        for stem, name in sprites:
            if not list(CONCEPTS.glob(f"{stem}_*.png")):
                fails.append(f"SPRITES entry {name!r} names concept source "
                             f"{stem!r}, but no {stem}_*.png exists in "
                             f"{CONCEPTS.relative_to(ENGINE.parent)}")
    else:
        print(f"check_dungeon_sprites: note: {CONCEPTS} absent, concept-source "
              "existence not checked")

    if fails:
        for f in fails:
            print(f"check_dungeon_sprites: {f}", file=sys.stderr)
        return 1

    print(f"dungeon-sprites-check: current — {len(want)} sprites, "
          f"edge {parse_const(gen_text, 'EDGE')}, palette {parse_const(gen_text, 'PAL_N')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
